/** Only known application messages are exposed; unknown provider details stay hidden. */
export function specialistMessage(raw: string, t: (key: string, vars?: Variables) => string): string {
 if (!raw) return "";
 for (const [key, value] of Object.entries(specialistMessages)) if (value.fr === raw) return t(key);
 const retained = " La demande est conservée ; « Reprendre l’état » consulte son état sans nouvelle génération.";
 if (raw.endsWith(retained)) return specialistMessage(raw.slice(0,-retained.length),t) + " " + t("publisher.retainedRequest");
 for (const [key, value] of Object.entries(specialistMessages)) {
   if (typeof value.fr !== "string" || !/\{[A-Za-z0-9_]+\}/.test(value.fr)) continue;
   const names: string[] = [];
   const escaped = value.fr.replace(/[.*+?^$()|[\]\\]/g,"\\$&");
   const pattern = escaped.replace(/\{([A-Za-z0-9_]+)\}/g,(_,name:string)=>{names.push(name);return "(.+?)";});
   const match = raw.match(new RegExp("^"+pattern+"$"));
   if (match) { const vars: Variables = {}; names.forEach((name,index)=>{const captured=match[index+1]; const caption=name==="field"?Object.entries(specialistMessages).find(([,entry])=>entry.fr===captured):undefined; vars[name]=caption?t(caption[0]):captured;}); return t(key,vars); }
 }
 return t("common.unknownError");
}
